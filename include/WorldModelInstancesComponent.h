/**
 * @brief Returns the model instances component's property table ("model_instances_component").
 * @returns The table (static, immutable).
 */
const PropertyTable* WorldModelInstancesComponent_GetPropertyTable(void);

/**
 * @brief Downcasts a component to a model instances component.
 * @param component The component, or NULL.
 * @returns The model instances component, or NULL when @p component is NULL or of another type.
 */
static inline WorldModelInstancesComponent* WorldModelInstancesComponent_FromComponent(WorldComponent* component)
{
    return ((component != NULL) && (component->_type == WorldComponentType_ModelInstances))
        ? (WorldModelInstancesComponent*)component : NULL;
}

/**
 * @brief Upcasts a model instances component to its base.
 * @param self The component; must not be NULL.
 * @returns The embedded base.
 */
static inline WorldComponent* WorldModelInstancesComponent_AsComponent(WorldModelInstancesComponent* self)
{
    return &self->Base;
}

/**
 * @brief Returns the borrowed asset name of the world model every copy draws (may be NULL); valid until it changes.
 * @param self The component; must not be NULL.
 * @returns The NUL-terminated asset name, in full ("tbp:desk"), or NULL.
 */
static inline const unsigned char* WorldModelInstancesComponent_GetWorldModel(const WorldModelInstancesComponent* self)
{
    return self->_worldModel;
}

/**
 * @brief Sets the world model every copy draws (a clone of @p worldModel; NULL draws nothing). The renderer resolves it at
 *        its next frame.
 * @param self The component; must not be NULL.
 * @param worldModel Borrowed asset name as written ("tree" is kept as "tbp:tree"), or NULL.
 * @returns Success; ErrorCode_IllegalArgument if @p self is NULL; ErrorCode_ArgumentOutOfRange if @p worldModel is not
 *          a valid asset name of at most WORLD_MODEL_COMPONENT_NAME_MAX_LENGTH bytes (nothing changes then).
 */
Error WorldModelInstancesComponent_SetWorldModel(WorldModelInstancesComponent* self, const unsigned char* worldModel);

/**
 * @brief Returns whether the copies are drawn with a variant of their world model.
 * @param self The component; must not be NULL.
 * @returns true while the variant named by WorldModelInstancesComponent_GetVariant is used.
 */
static inline bool WorldModelInstancesComponent_UsesVariant(const WorldModelInstancesComponent* self)
{
    return self->_usesVariant;
}

/**
 * @brief Switches the variant on or off (off: the world model's own materials). The variant's name is kept either way.
 * @param self The component; must not be NULL.
 * @param usesVariant Whether to use the variant.
 * @returns Success; ErrorCode_IllegalArgument if @p self is NULL.
 */
